-- Uma única tabela para os dois tipos de processo: "tipo" e "estado" são strings simples.
create table processo_pagamento (
    id          bigint generated by default as identity primary key,
    tipo        varchar(20)    not null,
    numero_cota varchar(30)    not null,
    valor       numeric(15, 2) not null,
    estado      varchar(30)    not null,
    versao      bigint         not null default 0
);

-- Histórico (R8): uma linha por transição, só com inclusões.
create table processo_transicao (
    id             bigint generated by default as identity primary key,
    processo_id    bigint       not null references processo_pagamento (id),
    estado_origem  varchar(30)  not null,
    estado_destino varchar(30)  not null,
    acao           varchar(30)  not null,
    ocorrido_em    timestamptz  not null,
    autor          varchar(100) not null,
    observacao     varchar(500)
);

create index ix_processo_estado on processo_pagamento (tipo, estado);
create index ix_transicao_processo on processo_transicao (processo_id);
