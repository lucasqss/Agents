-- Favorecidos do processo (R15, R29): quem recebe cada parte do valor. "ordem" guarda a ordem em que foram informados.
create table processo_favorecido (
    id          bigint generated by default as identity primary key,
    processo_id bigint         not null references processo_pagamento (id),
    ordem       integer        not null,
    nome        varchar(120)   not null,
    documento   varchar(14)    not null,
    papel       varchar(50)    not null,
    valor       numeric(15, 2) not null,
    constraint uk_favorecido_documento unique (processo_id, documento),
    constraint uk_favorecido_ordem unique (processo_id, ordem)
);

-- Implantação (R30): cada processo existente recebe UM favorecido, o cliente da cota (nome, CPF só com dígitos),
-- com o papel "titular" e o valor inteiro do processo. O nome é cortado em 120 caracteres, o tamanho da coluna.
insert into processo_favorecido (processo_id, ordem, nome, documento, papel, valor)
select p.id, 1, left(cl.nome, 120), regexp_replace(cl.cpf, '[^0-9]', '', 'g'), 'titular', p.valor
from processo_pagamento p
join cota c on c.id = p.cota_id
join cliente cl on cl.id = c.cliente_id;
