-- Alteração de valor e favorecidos com a concordância do cliente (R24 a R28).
-- O estado AGUARDANDO_CONCORDANCIA é só um texto novo em "estado"; não há CHECK a ajustar.

-- Alteração proposta pelo backoffice, guardada à parte enquanto o cliente não responde: no máximo uma por processo.
-- O valor e os favorecidos vigentes continuam em processo_pagamento e processo_favorecido até a concordância.
create table processo_alteracao_proposta (
    processo_id bigint         primary key references processo_pagamento (id),
    valor       numeric(15, 2) not null,
    motivo      varchar(500)   not null
);

-- Favorecidos propostos; mesma forma de processo_favorecido, com a regra de repetição dentro do conjunto novo.
create table processo_proposta_favorecido (
    id          bigint generated by default as identity primary key,
    processo_id bigint         not null references processo_alteracao_proposta (processo_id),
    ordem       integer        not null,
    nome        varchar(120)   not null,
    documento   varchar(14)    not null,
    papel       varchar(50)    not null,
    valor       numeric(15, 2) not null,
    constraint uk_proposta_favorecido_documento unique (processo_id, documento),
    constraint uk_proposta_favorecido_ordem unique (processo_id, ordem)
);

-- Histórico: valor vigente antes e valor pedido, só nas ações que alteram o valor (alterar e propor alteração).
alter table processo_transicao add column valor_anterior numeric(15, 2);
alter table processo_transicao add column valor_novo numeric(15, 2);
