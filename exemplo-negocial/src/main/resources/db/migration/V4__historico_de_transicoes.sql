-- Histórico: uma linha por mudança de estado do processo.
create table processo_transicao (
    id             bigint generated by default as identity primary key,
    processo_id    bigint       not null references processo_pagamento (id),
    estado_origem  varchar(30)  not null,
    estado_destino varchar(30)  not null,
    acao           varchar(30)  not null,
    ocorrido_em    timestamp with time zone not null,
    observacao     varchar(500)
);

create index ix_transicao_processo on processo_transicao (processo_id);
