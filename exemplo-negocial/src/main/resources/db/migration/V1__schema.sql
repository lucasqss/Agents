create table cliente (
    id   bigint generated by default as identity primary key,
    nome varchar(200) not null,
    cpf  varchar(14)  not null,
    constraint uk_cliente_cpf unique (cpf)
);

create table cota (
    id            bigint generated by default as identity primary key,
    numero        varchar(30)    not null,
    valor_credito numeric(15, 2) not null,
    cliente_id    bigint         not null references cliente (id),
    constraint uk_cota_numero unique (numero)
);

-- Uma única tabela para os dois tipos de processo: "tipo" e "estado" são strings simples.
create table processo_pagamento (
    id      bigint generated by default as identity primary key,
    cota_id bigint      not null references cota (id),
    tipo    varchar(20) not null,
    estado  varchar(30) not null
);

create index ix_cota_cliente on cota (cliente_id);
create index ix_processo_cota on processo_pagamento (cota_id);
create index ix_processo_tipo_estado on processo_pagamento (tipo, estado);
